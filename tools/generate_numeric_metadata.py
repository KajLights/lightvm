#!/usr/bin/env python3
"""Generate small C/Python metadata tables; independent wire fixtures stay manual."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = {'i32':1, 'f32':2, 'bool':4, 'q16':7}


def generate():
    baseline = json.loads((ROOT/'lightvm/release.json').read_text())['baseline']
    catalogue = json.loads((ROOT/'docs/design/numeric-operations.json').read_text())
    operations = sorted((o for o in catalogue['operations'] if o['implementation']=='runtime'),
                        key=lambda o:o['wire_id']['id'])
    assert len({o['wire_id']['id'] for o in operations}) == len(operations)
    records = {}
    c = '/* Generated by tools/generate_numeric_metadata.py; do not edit. */\n'
    c += f'_Static_assert(LBC_MAP_WORK_BUDGET=={catalogue["map_work_budget"]}, "kernel work budget");\n'
    for o in operations:
        assert not o['effects'], 'numeric operations must be pure'
        assert 0 < o['work_cost'] <= 255
        assert o['kernel_admitted'] and o['feature_floor']['release'] == o['kernel_feature_floor'] == baseline
        name, wire = o['wire_name'], o['wire_id']['id']
        c += f'_Static_assert({name}=={wire}, "numeric wire ID: {name}");\n'
        if 62 <= wire <= 71:
            c += f'_Static_assert(LVM_{name[1:]}=={name}-FABS, "native math enum: {name}");\n'
        records[name] = {'id':wire, 'signature':[TYPES[t] for t in [o['result'],*o['arguments']]],
                         'release':o['feature_floor']['release'], 'kernel_release':o['kernel_feature_floor'],
                         'work':o['work_cost'], 'effects':0, 'kernel':True}

    def initializer(record):
        sig = (record['signature']+[0])[:3]
        return '{{'+','.join(map(str,sig))+'},'+','.join(map(str,[
            record['work'],record['effects'],int(record['kernel'])]))+'}'

    c += 'static const LbcNumericMetadata numeric_metadata[]={\n'
    c += ''.join('    '+initializer(r)+', /* '+name+' */\n' for name,r in records.items() if r['id']>=40)
    c += '};\nLbcNumericMetadata lbc_numeric_metadata(unsigned op){\n'
    c += '    if(op>=QADD&&op<=FPOW)return numeric_metadata[op-QADD];\n    switch(op){\n'
    c += ''.join(f'    case {name}:return (LbcNumericMetadata){initializer(r)};\n' for name,r in records.items() if r['id']<40)
    c += '    default:return (LbcNumericMetadata){0};\n    }\n}\n'
    c += 'LbcNumericMetadata lbc_native_numeric_metadata(unsigned binding){\n    switch(binding){\n'
    natives = {}
    for o in operations:
        if 'existing_binding' not in o: continue
        binding = o['existing_binding']; r=records[o['wire_name']]
        assert binding['feature_floor']==r['release'] and binding['kernel_feature_floor']==r['kernel_release']
        natives[binding['id']]=o['wire_name']
        c += f'    case {binding["id"]}:return lbc_numeric_metadata({o["wire_name"]});\n'
    c += '    default:return (LbcNumericMetadata){0};\n    }\n}\n'
    work = '/* Generated by tools/generate_numeric_metadata.py; do not edit. */\n'
    work += 'extern const uint8_t lbc_instruction_work_costs[256];\n'
    work += 'static inline unsigned lbc_instruction_work(unsigned op){\n    return op<256?lbc_instruction_work_costs[op]:1;\n}\n'
    work += 'static inline unsigned lbc_native_instruction_work(unsigned binding){\n    switch(binding){\n'
    work += ''.join(f'    case {binding}:return {records[name]["work"]};\n' for binding,name in natives.items())
    work += ''.join(f'    case {o["binding"]}:return {o["work_cost"]};\n' for o in catalogue['native_noise_operations'])
    work += '    default:return 1;\n    }\n}\n'
    noise = catalogue['native_noise_operations']
    work += ''.join(f'/* {o["name"]}: native {o["binding"]}, work {o["work_cost"]}. */\n' for o in noise)
    costs = {int(op):weight for op,weight in catalogue['base_instruction_work'].items()}
    costs.update({r['id']:r['work'] for r in records.values()})
    assert all(0 <= op < 256 and 0 < weight <= 255 for op,weight in costs.items())
    c += 'const uint8_t lbc_instruction_work_costs[256]={\n'
    for first in range(0,256,8):
        c += '    '+','.join(str(costs.get(op,1)) for op in range(first,first+8))+',\n'
    c += '};\n'
    py = '# Generated by tools/generate_numeric_metadata.py; do not edit.\n'
    py += 'OPERATIONS = {\n'+''.join('    '+repr(k)+': '+repr(v)+',\n' for k,v in records.items())+'}\n'
    py += 'NATIVE_OPERATIONS = '+repr(natives)+'\n'
    py += 'BASE_WORK = '+repr({int(k):v for k,v in catalogue['base_instruction_work'].items()})+'\n'
    py += 'MAP_WORK_BUDGET = '+str(catalogue['map_work_budget'])+'\n'
    py += 'NOISE_OPERATIONS = '+repr({o['name']:{'binding':o['binding'], 'signature':[TYPES[t] for t in [o['result'],*o['arguments']]], 'work':o['work_cost']} for o in noise})+'\n'
    nc = '/* Generated by tools/generate_numeric_metadata.py; do not edit. */\n'
    nc += 'LvmNoiseSignature lvm_noise_signature(unsigned binding){\n    switch(binding){\n'
    for o in noise:
        assert not o['effects'] and o['kernel_admitted'] and o['feature_floor']==o['kernel_feature_floor']==baseline
        assert 0 < o['work_cost'] <= 255 and len(o['arguments']) <= 7
        nc += f'    case LVM_{o["name"].upper()}:return (LvmNoiseSignature)'+'{'+str(len(o['arguments']))+',{'+','.join(str(TYPES[t]) for t in o['arguments'])+'},'+str(o['work_cost'])+'};\n'
    nc += '    default:return (LvmNoiseSignature){0};\n    }\n}\n'
    nc += ''.join(f'_Static_assert(LVM_{o["name"].upper()}=={o["binding"]}, "noise binding");\n' for o in noise)
    return {'src/noise_metadata.inc':nc, 'src/numeric_metadata.inc':c, 'src/numeric_work.inc':work, 'lightvm/numeric_metadata.py':py}


if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    for name,text in generate().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=text: raise SystemExit(name+' is stale; regenerate numeric metadata')
        else:path.write_text(text)

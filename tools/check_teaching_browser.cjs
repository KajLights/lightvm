/* Browser acceptance with every remote request blocked: no controller or CDN. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } }), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const origin = process.env.LIGHTVM_EDITOR_URL || 'http://127.0.0.1:8765';
    await page.route('**/*', route => route.request().url().startsWith(origin + '/') ? route.continue() : route.abort());
    await page.goto(origin + '/#/editor');
    const checked = () => page.waitForFunction(() => document.querySelector('#check-state')?.textContent === 'All checks passed', null, { timeout: 30000 });
    await checked();
    const preview = page.getByRole('region', { name: 'Local light preview' });
    await preview.getByRole('button', { name: 'Start preview', exact: true }).click();
    await preview.getByText('Frame finished.', { exact: false }).waitFor();
    await preview.getByLabel('Show a ring').check();
    await preview.getByRole('button', { name: 'Next frame', exact: true }).click();
    await preview.getByText('Time: 0.033 seconds.', { exact: false }).waitFor();
    await preview.getByLabel('Step through the code').check();
    await preview.getByRole('button', { name: 'Start preview', exact: true }).click();
    await preview.getByLabel('Watch a value').waitFor();
    await preview.getByRole('button', { name: 'Next step', exact: true }).click();
    await page.screenshot({ path: path.join(root, 'build/teaching-browser-desktop.png'), fullPage: true });
    const bad = 'from lightvm import profile, render, rgb\nprofile("animation")\n@render\ndef draw(state, runtime, pixels):\n    café = 1; pixels[pixels.count] = rgb(20, 0, 0)\n';
    await page.evaluate(source => document.querySelector('.CodeMirror').CodeMirror.setValue(source), bad);
    await checked();
    await preview.getByLabel('Step through the code').uncheck();
    await preview.getByRole('button', { name: 'Start preview', exact: true }).click();
    await preview.getByRole('button', { name: 'Show the problem on line 5' }).waitFor();
    await preview.getByRole('button', { name: 'Show the problem on line 5' }).click();
    assert.deepEqual(await page.evaluate(() => document.querySelector('.CodeMirror').CodeMirror.getCursor()), { line: 4, ch: bad.split('\n')[4].indexOf('pixels') });
    await page.getByLabel('Choose a lesson').selectOption('08-controls');
    await page.getByRole('button', { name: 'Try the next change', exact: true }).click(); await checked();
    await page.getByText('Preview settings & inputs', { exact: true }).click();
    await page.getByLabel('Override warning').check();
    await page.locator('#draft-warning').fill('0.6');
    await preview.getByRole('button', { name: 'Start preview', exact: true }).click();
    await preview.getByText('Frame finished.', { exact: false }).waitFor();
    await preview.getByLabel('progress', { exact: true }).fill('0.7');
    await preview.getByRole('button', { name: 'Next frame', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('.local-preview circle')].every(pixel => pixel.getAttribute('fill') === 'rgb(40, 0, 0)'));
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Save locally', exact: false }).click();
    const download = await downloadEvent, saved = path.join(root, 'build/teaching-saved.lightvm.json');
    await download.saveAs(saved);
    const recipe = JSON.parse(require('node:fs').readFileSync(saved, 'utf8'));
    assert.equal(recipe.settings.warning, 0.6); assert.equal(recipe.inputs.progress.value, 0.7);
    await page.getByLabel('Choose a lesson').selectOption('01-first-lights'); await checked();
    await page.locator('#source-file').setInputFiles(saved); await checked();
    await preview.getByRole('button', { name: 'Start preview', exact: true }).click();
    await preview.getByText('Frame finished.', { exact: false }).waitFor();
    assert.equal(await preview.getByLabel('progress', { exact: true }).inputValue(), '0.7');
    await page.waitForFunction(() => [...document.querySelectorAll('.local-preview circle')].every(pixel => pixel.getAttribute('fill') === 'rgb(40, 0, 0)'));
    await page.getByLabel('Language', { exact: true }).selectOption('blocks'); await checked();
    await page.getByLabel('Load example').selectOption('blocks_stars'); await checked();
    await page.getByRole('button', { name: 'Show all blocks', exact: true }).click();
    assert.ok(await page.locator('.blocklySvg').count());
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(root, 'build/teaching-browser-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Teaching tools fit a narrow screen');
    assert.deepEqual(errors, []);
    console.log('Offline compiler, local preview, ring, frame/line stepping, source fault, lessons, settings/input save/import, Blocks and narrow screen: passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

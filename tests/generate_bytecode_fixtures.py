import sys
"""Regenerate the small C test fixtures: python tests/generate_bytecode_fixtures.py."""
from pathlib import Path
from bytecode_fixtures import PREFIX, color, fault, program
fixtures = {
    "fault_lbc": fault(),
    "render_lbc": color(255, 128, 0),
    "control_lbc": program(PREFIX + "@render\ndef draw(ctx,runtime,pixels):\n ms=int(runtime.delta*1000.0)\n pixels[0]=rgb(0,ms//256,ms%256)\n"),
    "slot_lbc": program(PREFIX + "from lightvm import setting\n@init\ndef setup(ctx,runtime):\n ctx.seed=setting(4)\n ctx.phase=-1\n@render\ndef draw(ctx,runtime,pixels):\n ctx.phase+=1\n pixels[pixels.count-1]=rgb(0,0,ctx.phase+int(runtime.delta*1000.0)+ctx.seed)\n"),
}
text = "// Generated by tests/generate_bytecode_fixtures.py.\n"
for name, data in fixtures.items():
    text += f"_Alignas(4) static const uint8_t {name}[] = {{\n"
    text += "".join("    " + ",".join(f"0x{x:02x}" for x in data[i:i+16]) + ",\n" for i in range(0, len(data), 16))
    text += "};\n"
output = Path(__file__).with_name("bytecode_fixtures.h")
if '--check' in sys.argv:
    if output.read_text() != text:
        raise SystemExit(str(output) + ' is stale; regenerate fixtures')
else:
    output.write_text(text)
